/**
 * `npm run bench`: runs Redline over public, labelled misconfiguration test cases from KICS and
 * gixy (see bench/sources.ts and bench/README.md) and reports precision, recall and false
 * positives per file type.
 *
 * Each case is a file plus the Redline rule(s) it maps to. A positive file is found when one of
 * those rules fires; a negative file is a false positive when one of them fires. Other rules
 * firing is not counted either way: the other tools' negative files are only clean for the one
 * check they test.
 *
 * Cases are split once, by a hash of their path, into a development set (about 60%) and a
 * held-out test set. Rules are tuned on the development set only (`--dev` lists its misses);
 * the test set is reported to show whether those changes generalise.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { audit, KIND_NAME, type Kind } from "../packages/core/src/index";
import { PLATFORM_KIND, type KicsQuery } from "../bench/sources";

type Case = { source: "kics" | "gixy"; file: string; expect: "positive" | "negative"; rule?: string; rules?: string[]; platform?: KicsQuery["platform"]; queryName?: string; plugin?: string };

const ROOT = join(import.meta.dirname, "..", "bench");
const manifest = JSON.parse(readFileSync(join(ROOT, "fixtures", "manifest.json"), "utf8")) as { kics: { ref: string }; gixy: { name: string; version: string }; cases: Case[] };

export const split = (file: string): "dev" | "test" => (createHash("sha256").update(file).digest()[0] < 154 ? "dev" : "test");

type Tally = { tp: number; fn: number; fp: number; tn: number; errors: number };
const empty = (): Tally => ({ tp: 0, fn: 0, fp: 0, tn: 0, errors: 0 });
const KINDS: Kind[] = ["dockerfile", "compose", "kubernetes", "nginx", "sshd"];

const results = manifest.cases.map((c) => {
  const kind: Kind = c.source === "kics" ? PLATFORM_KIND[c.platform!] : "nginx";
  const rules = c.rules ?? [c.rule!];
  const text = readFileSync(join(ROOT, "fixtures", c.file), "utf8");
  const t0 = performance.now();
  const report = audit(c.file, text, kind);
  const ms = performance.now() - t0;
  const fired = report.findings.some((f) => rules.includes(f.rule));
  const ok = fired === (c.expect === "positive");
  return { ...c, kind, rules, set: split(c.file), fired, ok, errors: report.errors, ms };
});

const tally = (rows: typeof results) => {
  const by = Object.fromEntries(KINDS.map((k) => [k, empty()])) as Record<Kind, Tally>;
  const all = empty();
  for (const r of rows) {
    for (const t of [by[r.kind], all]) {
      const key = r.expect === "positive" ? (r.fired ? "tp" : "fn") : r.fired ? "fp" : "tn";
      t[key]++;
      if (r.errors.length) t.errors++;
    }
  }
  return { by, all };
};
const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "n/a");
const precision = (t: Tally) => pct(t.tp, t.tp + t.fp);
const recall = (t: Tally) => pct(t.tp, t.tp + t.fn);

const table = (rows: typeof results) => {
  const { by, all } = tally(rows);
  const line = (name: string, t: Tally) => `| ${name} | ${t.tp + t.fn} | ${t.fp + t.tn} | ${precision(t)} | ${recall(t)} | ${t.fp} | ${t.errors} |`;
  return [
    "| File type | Positive files | Negative files | Precision | Recall | False positives | Parse errors |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...KINDS.filter((k) => by[k].tp + by[k].fn + by[k].fp + by[k].tn).map((k) => line(KIND_NAME[k], by[k])),
    line("**All**", all),
  ].join("\n");
};

const misses = (rows: typeof results) =>
  rows
    .filter((r) => !r.ok)
    .map((r) => `- ${r.expect === "positive" ? "missed" : "false positive"}: \`${r.file}\` (${r.rules.join("/")}${r.queryName ? `, KICS "${r.queryName}"` : ""})`)
    .join("\n");

if (process.argv.includes("--dev")) {
  console.log(table(results.filter((r) => r.set === "dev")));
  console.log(misses(results.filter((r) => r.set === "dev")) || "No misses on the development set.");
  process.exit(0);
}

const test = results.filter((r) => r.set === "test");
const ms = results.reduce((s, r) => s + r.ms, 0) / results.length;
const md = `# Benchmark results

Generated by \`npm run bench\`. Sources: KICS \`${manifest.kics.ref}\` (Apache-2.0) query test cases for Dockerfile,
Docker Compose and Kubernetes; ${manifest.gixy.name} ${manifest.gixy.version} (MPL-2.0) plugin tests for nginx. No public
labelled test suite for \`sshd_config\` was found, so sshd is not in this benchmark.

## Held-out test set (${test.length} files, not used while tuning rules)

${table(test)}

## All ${results.length} files

${table(results)}

Average time per file: ${ms.toFixed(2)} ms.

## Files Redline gets wrong in the held-out set

${misses(test) || "None."}
`;
writeFileSync(join(ROOT, "RESULTS.md"), md);
writeFileSync(
  join(ROOT, "results.json"),
  JSON.stringify({ test: tally(test), all: tally(results), cases: results.map(({ file, set, expect, rules, fired, ok }) => ({ file, set, expect, rules, fired, ok })) }, null, 1) + "\n",
);
// The web app's lab report shows the same numbers; no timings, so the file only changes with the rules.
const baseline = JSON.parse(readFileSync(join(ROOT, "baseline.json"), "utf8")) as { test: ReturnType<typeof tally> };
writeFileSync(
  join(import.meta.dirname, "..", "apps", "web", "public", "benchmark.json"),
  JSON.stringify({ sources: { kics: manifest.kics.ref, gixy: `${manifest.gixy.name} ${manifest.gixy.version}` }, files: results.length, testFiles: test.length, test: tally(test), all: tally(results), baselineTest: baseline.test }, null, 1) + "\n",
);
console.log(md);
